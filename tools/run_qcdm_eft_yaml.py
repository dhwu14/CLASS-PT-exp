#!/usr/bin/env python3
"""Run the coupled c-c' CLASS-PT EFTofLSS validation workflow from YAML.

DW: This driver converts a human-readable YAML configuration into a CLASS .ini,
runs the executable, validates the decomposed outputs, and writes cumulative CSV
files that isolate IR, one-loop, counterterm, and stochastic effects.
"""

from __future__ import annotations

import argparse
import csv
import glob
import math
import os
from pathlib import Path
import subprocess
import sys
from typing import Any, Dict, Iterable, Mapping

try:
    import yaml
except ImportError as exc:  # pragma: no cover - exercised only on missing dependency
    raise SystemExit("PyYAML is required: python3 -m pip install pyyaml") from exc

try:
    import numpy as np
except ImportError as exc:  # pragma: no cover - exercised only on missing dependency
    raise SystemExit("NumPy is required: python3 -m pip install numpy") from exc


# DW: Preserve YAML insertion order so the generated CLASS file is easy to audit.
def _flatten_parameters(base: Mapping[str, Any], profile: Mapping[str, Any]) -> Dict[str, Any]:
    merged: Dict[str, Any] = dict(base)
    merged.update(profile)
    return merged


# DW: Render booleans in the yes/no form expected by CLASS while leaving lists readable.
def _class_value(value: Any) -> str:
    if isinstance(value, bool):
        return "yes" if value else "no"
    if isinstance(value, (list, tuple)):
        return ",".join(str(item) for item in value)
    return str(value)


# DW: Delete only files beginning with the configured output root, never the source tree.
def _clean_outputs(root: Path) -> None:
    for name in glob.glob(str(root) + "*"):
        path = Path(name)
        if path.is_file() or path.is_symlink():
            path.unlink()


# DW: Write an explicit generated .ini so every YAML-to-CLASS parameter is reproducible.
def _write_ini(path: Path, parameters: Mapping[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8") as handle:
        handle.write("# DW: generated by tools/run_qcdm_eft_yaml.py; edit the YAML, not this file.\n")
        for key, value in parameters.items():
            if value is None:
                continue
            handle.write(f"{key} = {_class_value(value)}\n")


# DW: Read numeric CLASS-style tables while retaining strict two-dimensional shape checks.
def _load_table(path: Path, minimum_columns: int) -> np.ndarray:
    data = np.loadtxt(path, comments="#", ndmin=2)
    if data.ndim != 2 or data.shape[1] < minimum_columns:
        raise RuntimeError(
            f"{path} has shape {data.shape}; expected at least {minimum_columns} columns"
        )
    if not np.all(np.isfinite(data)):
        bad = np.argwhere(~np.isfinite(data))[0]
        raise RuntimeError(f"Non-finite value in {path} at row {bad[0]}, column {bad[1]}")
    return data


# DW: Use a scale-aware closure test for cumulative spectra printed at finite precision.
def _assert_close(label: str, lhs: np.ndarray, rhs: np.ndarray, rtol: float = 3.0e-9) -> None:
    scale = np.maximum.reduce([np.abs(lhs), np.abs(rhs), np.ones_like(lhs)])
    error = np.max(np.abs(lhs - rhs) / scale)
    if not math.isfinite(float(error)) or error > rtol:
        raise RuntimeError(f"{label} closure failed: maximum scaled residual = {error:.6e}")


# DW: Write CSV without silently changing the scientific units or column ordering.
def _write_csv(path: Path, header: Iterable[str], rows: np.ndarray) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.writer(handle)
        writer.writerow(list(header))
        writer.writerows(rows.tolist())


# DW: Convert the native matter diagnostic into a cumulative, analysis-ready CSV.
def _process_matter(source: Path, output: Path) -> Dict[str, float]:
    """Process the current 25-column exact-QS matter breakdown."""
    d = _load_table(source, 25)
    (
        k,
        pcluster_linear,
        ptotal_linear,
        pcluster_tree,
        ptotal_tree,
        delta_ir_total,
        p22_cluster,
        p13_cluster,
        p1loop_total,
        p12eq_unit_cluster,
        p12ortho_unit_cluster,
        ppng_total,
        p_after_loops_png,
        pct_mm,
        pct_mr,
        pct_all,
        p_after_ct,
        pstoch,
        ptotal_eft,
        frac_ir_native,
        frac_1loop_native,
        frac_png_native,
        frac_ct_native,
        frac_stoch_native,
        total_over_linear_native,
    ) = (d[:, i] for i in range(25))

    # Current writer outputs cluster P22/P13 but a total-matter P1loop after
    # multiplying by f_cluster^2, so do not compare p1loop_total directly with
    # p22_cluster+p13_cluster here.
    _assert_close("Delta_IR = P_total_tree_IR - P_total_linear",
                  delta_ir_total, ptotal_tree - ptotal_linear)
    _assert_close("P_ct_all = P_ct_mm + P_ct_mr", pct_all, pct_mm + pct_mr)
    _assert_close("P_after_loops_PNG = P_total_tree_IR + P_1loop_total + PPNG",
                  p_after_loops_png, ptotal_tree + p1loop_total + ppng_total)
    _assert_close("P_after_ct = P_after_loops_PNG + P_ct_all",
                  p_after_ct, p_after_loops_png + pct_all)
    _assert_close("P_total_EFT = P_after_ct + P_stoch",
                  ptotal_eft, p_after_ct + pstoch)

    denom = np.where(np.abs(ptotal_linear) > np.finfo(float).tiny, ptotal_linear, np.nan)
    frac_ir = delta_ir_total / denom
    frac_loop = p1loop_total / denom
    frac_png = ppng_total / denom
    frac_ct = pct_all / denom
    frac_stoch = pstoch / denom
    total_over_linear = ptotal_eft / denom

    # The native fractional columns are useful regression checks as well.
    _assert_close("native frac_IR", frac_ir_native, frac_ir)
    _assert_close("native frac_1loop", frac_1loop_native, frac_loop)
    _assert_close("native frac_PNG", frac_png_native, frac_png)
    _assert_close("native frac_ct", frac_ct_native, frac_ct)
    _assert_close("native frac_stoch", frac_stoch_native, frac_stoch)
    _assert_close("native total_over_linear", total_over_linear_native, total_over_linear)

    rows = np.column_stack(
        [
            k,
            pcluster_linear,
            ptotal_linear,
            pcluster_tree,
            ptotal_tree,
            delta_ir_total,
            p22_cluster,
            p13_cluster,
            p1loop_total,
            p12eq_unit_cluster,
            p12ortho_unit_cluster,
            ppng_total,
            p_after_loops_png,
            pct_mm,
            pct_mr,
            pct_all,
            p_after_ct,
            pstoch,
            ptotal_eft,
            frac_ir,
            frac_loop,
            frac_png,
            frac_ct,
            frac_stoch,
            total_over_linear,
        ]
    )
    _write_csv(
        output,
        [
            "k_h_Mpc",
            "P_cluster_linear_Mpch3",
            "P_total_linear_Mpch3",
            "P_cluster_tree_IR_Mpch3",
            "P_total_tree_IR_Mpch3",
            "Delta_IR_total_Mpch3",
            "P22_cluster_Mpch3",
            "P13_cluster_Mpch3",
            "P_1loop_total_Mpch3",
            "P12eq_unit_cluster_Mpch3",
            "P12ortho_unit_cluster_Mpch3",
            "P_PNG_total_Mpch3",
            "P_after_loops_PNG_Mpch3",
            "P_counterterm_mm_Mpch3",
            "P_counterterm_mr_Mpch3",
            "P_counterterm_all_Mpch3",
            "P_after_counterterm_Mpch3",
            "P_stochastic_k4_Mpch3",
            "P_total_EFTofLSS_Mpch3",
            "Delta_IR_over_Plinear_total",
            "P_1loop_over_Plinear_total",
            "P_PNG_over_Plinear_total",
            "P_counterterm_over_Plinear_total",
            "P_stochastic_over_Plinear_total",
            "P_total_over_Plinear_total",
        ],
        rows,
    )
    return {
        "matter_rows": float(len(k)),
        "max_abs_ir_fraction": float(np.nanmax(np.abs(frac_ir))),
        "max_abs_loop_fraction": float(np.nanmax(np.abs(frac_loop))),
        "max_abs_png_fraction": float(np.nanmax(np.abs(frac_png))),
        "max_abs_counterterm_fraction": float(np.nanmax(np.abs(frac_ct))),
        "max_abs_stochastic_fraction": float(np.nanmax(np.abs(frac_stoch))),
        "min_k_h_Mpc": float(np.min(k)),
        "max_k_h_Mpc": float(np.max(k)),
    }


# DW: Add cumulative columns to the real-space tracer decomposition and verify its sum rule.
def _process_tracer(source: Path, output: Path) -> Dict[str, float]:
    """Process the current 10-column exact-QS real-space tracer breakdown."""
    d = _load_table(source, 10)
    k, tree, p22, p13, p12eq, p12ortho, ppng, pct, pstoch, total = (
        d[:, i] for i in range(10)
    )
    ploop = p22 + p13
    after_loop_png = tree + ploop + ppng
    after_ct = after_loop_png + pct
    _assert_close("tracer P_total sum", total, after_ct + pstoch)
    denom = np.where(np.abs(tree) > np.finfo(float).tiny, tree, np.nan)
    rows = np.column_stack(
        [
            k,
            tree,
            p22,
            p13,
            ploop,
            p12eq,
            p12ortho,
            ppng,
            after_loop_png,
            pct,
            after_ct,
            pstoch,
            total,
            ploop / denom,
            ppng / denom,
            pct / denom,
            pstoch / denom,
            total / denom,
        ]
    )
    _write_csv(
        output,
        [
            "k_h_Mpc",
            "P_tracer_tree_Mpch3",
            "P22_tracer_Mpch3",
            "P13_tracer_Mpch3",
            "P_1loop_tracer_Mpch3",
            "P12eq_unit_tracer_Mpch3",
            "P12ortho_unit_tracer_Mpch3",
            "P_PNG_tracer_Mpch3",
            "P_tracer_after_loops_PNG_Mpch3",
            "P_tracer_counterterm_Mpch3",
            "P_tracer_after_counterterm_Mpch3",
            "P_tracer_stochastic_Mpch3",
            "P_tracer_total_Mpch3",
            "P_1loop_over_tree",
            "P_PNG_over_tree",
            "P_counterterm_over_tree",
            "P_stochastic_over_tree",
            "P_total_over_tree",
        ],
        rows,
    )
    return {"tracer_rows": float(len(k))}


# DW: Expose the net beyond-tree correction in each redshift-space multipole.
def _process_multipoles(source: Path, output: Path) -> Dict[str, float]:
    d = _load_table(source, 7)
    k, p0, p2, p4, t0, t2, t4 = (d[:, i] for i in range(7))
    rows = np.column_stack([k, t0, p0 - t0, p0, t2, p2 - t2, p2, t4, p4 - t4, p4])
    _write_csv(
        output,
        [
            "k_h_Mpc",
            "P0_tree_Mpch3",
            "P0_beyond_tree_Mpch3",
            "P0_total_Mpch3",
            "P2_tree_Mpch3",
            "P2_beyond_tree_Mpch3",
            "P2_total_Mpch3",
            "P4_tree_Mpch3",
            "P4_beyond_tree_Mpch3",
            "P4_total_Mpch3",
        ],
        rows,
    )
    return {"multipole_rows": float(len(k))}


# DW: Locate a unique CLASS output and fail loudly on absent or ambiguous products.
def _unique_output(root: Path, suffix: str) -> Path:
    matches = [Path(item) for item in glob.glob(str(root) + "*" + suffix)]
    if len(matches) != 1:
        raise RuntimeError(f"Expected one output matching {root}*{suffix}; found {matches}")
    return matches[0]


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Run and validate the c-c' exact-time CLASS-PT EFTofLSS YAML workflow."
    )
    parser.add_argument("yaml_file", type=Path)
    parser.add_argument("--profile", default=None, help="Profile under the YAML profiles mapping")
    parser.add_argument("--no-run", action="store_true", help="Only postprocess existing output files")
    args = parser.parse_args()

    config_path = args.yaml_file.resolve()
    project_root = Path(__file__).resolve().parents[1]
    config = yaml.safe_load(config_path.read_text(encoding="utf-8"))
    if not isinstance(config, dict):
        raise SystemExit("The YAML top level must be a mapping")

    run_cfg = config.get("run", {})
    profiles = config.get("profiles", {})
    profile_name = args.profile or run_cfg.get("default_profile", "smoke")
    if profile_name not in profiles:
        raise SystemExit(f"Unknown profile {profile_name!r}; available: {sorted(profiles)}")

    params = _flatten_parameters(config.get("parameters", {}), profiles[profile_name])
    root_value = str(run_cfg.get("output_root", "output/qcdm_eft_breakdown"))
    output_root = (project_root / root_value).resolve() if not Path(root_value).is_absolute() else Path(root_value)
    generated_value = str(
        run_cfg.get("generated_ini", f"output/{output_root.name}.{profile_name}.generated.ini")
    )
    generated_ini = (
        (project_root / generated_value).resolve()
        if not Path(generated_value).is_absolute()
        else Path(generated_value)
    )
    executable_value = str(run_cfg.get("executable", "./class"))
    executable = (
        (project_root / executable_value).resolve()
        if not Path(executable_value).is_absolute()
        else Path(executable_value)
    )

    params["root"] = str(output_root)
    output_root.parent.mkdir(parents=True, exist_ok=True)
    if bool(run_cfg.get("clean_previous", True)) and not args.no_run:
        _clean_outputs(output_root)
    _write_ini(generated_ini, params)

    if not args.no_run:
        if not executable.exists():
            raise SystemExit(f"CLASS executable not found: {executable}; run 'make class' first")
        log_path = Path(str(output_root) + "_run.log")
        # DW: Execute synchronously and preserve the full CLASS log next to the spectra.
        with log_path.open("w", encoding="utf-8") as log:
            completed = subprocess.run(
                [str(executable), str(generated_ini)],
                cwd=project_root,
                stdout=log,
                stderr=subprocess.STDOUT,
                text=True,
                check=False,
            )
        if completed.returncode != 0:
            tail = "\n".join(log_path.read_text(encoding="utf-8", errors="replace").splitlines()[-40:])
            raise SystemExit(f"CLASS failed with return code {completed.returncode}. Log tail:\n{tail}")

    matter_source = _unique_output(output_root, "qcdm_pt_matter_breakdown.dat")
    matter_csv = Path(str(output_root) + "_matter_effects.csv")
    summary = _process_matter(matter_source, matter_csv)

    tracer_source = _unique_output(output_root, "qcdm_pt_tracer_real.dat")
    tracer_csv = Path(str(output_root) + "_tracer_effects.csv")
    summary.update(_process_tracer(tracer_source, tracer_csv))

    multipole_source = _unique_output(output_root, "qcdm_pt_multipoles.dat")
    multipole_csv = Path(str(output_root) + "_multipole_effects.csv")
    summary.update(_process_multipoles(multipole_source, multipole_csv))

    summary_path = Path(str(output_root) + "_EFT_SUMMARY.txt")
    with summary_path.open("w", encoding="utf-8") as handle:
        handle.write("DW: coupled c-c' exact-time EFTofLSS validation summary\n")
        handle.write(f"profile = {profile_name}\n")
        handle.write(f"generated_ini = {generated_ini}\n")
        handle.write(f"native_matter_breakdown = {matter_source}\n")
        handle.write(f"matter_cumulative_csv = {matter_csv}\n")
        handle.write(f"tracer_cumulative_csv = {tracer_csv}\n")
        handle.write(f"multipole_cumulative_csv = {multipole_csv}\n")
        for key, value in summary.items():
            handle.write(f"{key} = {value:.12e}\n")
        handle.write("\nInterpretation:\n")
        handle.write("P_tree_IR = tree-level spectrum after the configured IR setting; for the exact-QS production branch with IR resummation=no, Delta_IR should be zero.\n")
        handle.write("P_after_1loop = P_tree_IR + P22 + P13.\n")
        handle.write("P_after_counterterm adds independent fitted k^2 P_mm and k^2 P_mr matter EFT terms.\n")
        handle.write("P_total_EFTofLSS additionally adds the conservation-compatible fitted k^4 matter stochastic term.\n")
        handle.write("Bias, tracer counterterms, and redshift-space stochastic terms are shown in the tracer/multipole products.\n")

    print(f"DW: CLASS YAML profile '{profile_name}' passed all cumulative-spectrum closure tests.")
    print(f"DW: matter effects:    {matter_csv}")
    print(f"DW: tracer effects:    {tracer_csv}")
    print(f"DW: multipole effects: {multipole_csv}")
    print(f"DW: summary:           {summary_path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
